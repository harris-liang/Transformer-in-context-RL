"""Train transformers to implement in-context SARSA and Actor-Critic updates."""

import argparse
import json
from pathlib import Path

import numpy as np
import torch

from model import Transformer, teacher_update
from paper_protocol import PROTOCOL, PaperTasks, PaperPrompt


EXPERIMENTS = ("sarsa", "ac", "mountaincar", "relu", "relu2", "softmax", "softmax2", "ac-raw")
BUDGETS = (100, 500, 1000, 5000, 10000, 15000)


def default_config(experiment):
    if experiment not in EXPERIMENTS:
        raise ValueError(f"Unknown experiment: {experiment}")
    ac = experiment in {"ac", "ac-raw"}
    mountaincar = experiment == "mountaincar"
    return dict(protocol=PROTOCOL, experiment=experiment, algorithm="ac" if ac else "sarsa",
                family="mountaincar" if mountaincar else "random",
                d=9 if ac else 36, m=36 if ac else 0,
                nS=None if mountaincar else 9, nA=3 if mountaincar else 4,
                gamma=0.99 if mountaincar else 0.5,
                epsilon=0.1, window=20, horizon=1000,
                tasks=15000 if experiment == "ac-raw" else (10000 if mountaincar else 5000),
                seed=7 if mountaincar else 2, alpha=0.2, beta=0.8,
                lr=1e-3, decay=0.997 if mountaincar else 0.99,
                activation="relu" if experiment.startswith("relu") else
                ("softmax" if experiment.startswith("softmax") else "linear"),
                heads=2 if experiment.endswith("2") else 1, raw=experiment == "ac-raw",
                **({"feature_rotation": True} if mountaincar else {}))


def make_model(config):
    return Transformer(config["algorithm"], config["d"], config["m"],
                       activation=config["activation"], heads=config["heads"])


def load_checkpoint(path):
    checkpoint = torch.load(path, map_location="cpu", weights_only=True)
    if checkpoint.get("format_version") != 1:
        raise ValueError("Use a checkpoint generated by this version of train.py")
    with torch.random.fork_rng(devices=[]):
        model = make_model(checkpoint["config"])
    model.load_state_dict(checkpoint["state_dict"])
    return model.eval(), checkpoint["config"]


def train(config, out):
    config = dict(config)
    n, horizon, tasks = config["window"], config["horizon"], config["tasks"]
    if tasks < 1 or n < 1 or horizon < 2 * n or horizon % n:
        raise ValueError("Need tasks>0 and horizon a multiple of window, at least 2*window")
    out = Path(out)
    if out.exists() and any(out.iterdir()):
        raise FileExistsError(f"Output directory is not empty: {out}; choose a new --out")
    out.mkdir(parents=True, exist_ok=True)
    (out / "config.json").write_text(json.dumps(config, indent=2) + "\n")
    torch.manual_seed(config["seed"])
    tasks_stream = PaperTasks(config)
    model = make_model(config)
    optimizer = torch.optim.Adam(model.parameters(), lr=config["lr"], weight_decay=0)
    scheduler = torch.optim.lr_scheduler.ExponentialLR(optimizer, gamma=config["decay"])
    losses, snapshots = [], {}
    checkpoint_path = None
    for task_index in range(tasks):
        task = tasks_stream.draw()
        prompt = PaperPrompt(task, config, tasks_stream.rng)
        total_loss = 0.0
        for window_index in range(horizon // n - 1):
            H, teacher_H = prompt.H, prompt.teacher_H
            target = teacher_update(teacher_H, config["algorithm"], config["d"],
                                    config["m"], config["alpha"], config["beta"])
            optimizer.zero_grad(set_to_none=True)
            prediction = model.predict(H)
            if config["algorithm"] == "ac":
                m = config["m"]
                loss = (0.5 * torch.norm(target[:m] - prediction[:m], p=2) ** 2
                        + 0.5 * torch.norm(target[m:] - prediction[m:], p=2) ** 2)
            else:
                loss = torch.norm(target - prediction, p=2) ** 2
            if not torch.isfinite(loss) or float(loss.detach()) > 1e6:
                raise RuntimeError(f"Training diverged at task {task_index + 1}, window {window_index}")
            loss.backward()
            optimizer.step()
            total_loss += float(loss.detach())
            prompt.step(target)
        losses.append(total_loss / (horizon // n - 1))
        if task_index % 10 == 0:
            scheduler.step()
        K = task_index + 1
        if K in BUDGETS or K == tasks:
            checkpoint_path = out / f"checkpoint_{K}.pt"
            torch.save(dict(format_version=1, config=config, tasks_completed=K,
                            state_dict={k: v.detach().cpu().clone() for k, v in model.state_dict().items()}),
                       checkpoint_path)
            snapshots[str(K)] = dict(loss_last50=float(np.mean(losses[-50:])),
                                     cosine=model.cosine_similarity(config["alpha"], config["beta"]))
            np.savez_compressed(out / "training.npz", tasks=np.arange(1, K + 1), loss=losses)
            (out / "metrics.json").write_text(json.dumps(snapshots, indent=2) + "\n")
        if task_index % 100 == 0 or K == tasks:
            print(f"{config['experiment']} K={K}/{tasks} loss={losses[-1]:.3e}", flush=True)
    return checkpoint_path


def plot_training(checkpoint, show=False, output_dir=None):
    import matplotlib
    if not show:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    checkpoint = Path(checkpoint)
    model, config = load_checkpoint(checkpoint)
    completed = torch.load(checkpoint, map_location="cpu", weights_only=True)["tasks_completed"]
    out = checkpoint.parent if output_dir is None else Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    with np.load(checkpoint.parent / "training.npz") as history:
        keep = history["tasks"] <= completed
        tasks, losses = history["tasks"][keep], history["loss"][keep]
    car = config["family"] == "mountaincar"
    indices = np.unique(np.r_[np.arange(0, len(tasks), 25 if car else 50), len(tasks) - 1])

    def save(fig, name, dpi=350, tight=True):
        for extension in (("pdf", "png") if car else ("png", "pdf")):
            fig.savefig(out / f"{name}.{extension}", dpi=dpi,
                        bbox_inches="tight" if tight else None)
        if show:
            plt.show()
        plt.close(fig)

    if car:
        style = {"font.family": "DejaVu Serif", "font.size": 10,
                 "text.color": "black", "axes.labelcolor": "black",
                 "xtick.color": "black", "ytick.color": "black",
                 "pdf.fonttype": 42, "ps.fonttype": 42}
        with plt.rc_context(style):
            P, V = model.P[0].detach().numpy(), model.V[0].detach().numpy()
            blocks = [P, V, P[:73, 73:], V[74:, :73]]
            titles = [r"(a) $\mathbf{P}$", r"(b) $\mathbf{V}$",
                      r"(c) $\mathbf{P}_{12}$", r"(d) $\bar{\mathbf{V}}_{21}$"]
            fig, axes = plt.subplots(2, 2, figsize=(7, 5.9), layout="constrained")
            for ax, block, title in zip(axes.flat, blocks, titles):
                limit = max(float(np.abs(block).max()), 1e-8)
                im = ax.imshow(block, cmap="viridis", vmin=-limit, vmax=limit,
                               interpolation="none", aspect="auto", rasterized=True)
                ax.set_title(title, fontsize=11)
                ax.set(xlabel="Column", ylabel="Row")
                fig.colorbar(im, ax=ax, fraction=.047, pad=.035)
            save(fig, "mountaincar_parameters", dpi=300)
            fig, ax = plt.subplots(figsize=(6.2, 2.7), layout="constrained")
            ax.semilogy(tasks[indices], losses[indices], color="#2563b0", linewidth=.9)
            ax.set(xlabel="Training tasks processed", ylabel="Mean squared prediction error",
                   xlim=(0, completed))
            ax.grid(True, which="major", color="0.88", linewidth=.5)
            save(fig, "mountaincar_loss", dpi=300)
        return

    label = "Actor-Critic" if config["algorithm"] == "ac" else "SARSA"
    suffix = "_AC" if config["algorithm"] == "ac" else ""
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(np.arange(len(indices)) * 50, losses[indices])
    ax.set_xlabel("Iteration", fontsize=16)
    ax.set_ylabel("Loss", fontsize=16)
    ax.set_title(f"{label} Transformer training loss", fontsize=18)
    ax.set_ylim(0, 1e-3)
    ax.tick_params(axis="both", labelsize=14)
    fig.tight_layout()
    save(fig, "loss" + suffix, dpi=100, tight=False)
    for head, (P, V) in enumerate(zip(model.P, model.V)):
        tag = "last" if len(model.P) == 1 else f"head{head + 1}"
        for name, matrix in (("P", P), ("V", V)):
            fig, ax = plt.subplots(figsize=(4.5, 4), constrained_layout=True)
            im = ax.imshow(matrix.detach().numpy(), cmap="viridis", interpolation="nearest",
                           vmin=-1.2, vmax=1.2)
            bar = fig.colorbar(im, ax=ax, shrink=.85, pad=.03)
            ax.set_title(f"{name} ({tag})", fontsize=16, pad=10)
            ax.tick_params(axis="both", labelsize=12)
            bar.ax.tick_params(labelsize=12)
            save(fig, f"{name}_{tag}{suffix}")

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("experiment", choices=EXPERIMENTS)
    parser.add_argument("--tasks", type=int)
    parser.add_argument("--seed", type=int)
    parser.add_argument("--window", type=int)
    parser.add_argument("--horizon", type=int)
    parser.add_argument("--out", type=Path)
    parser.add_argument("--threads", type=int, default=1)
    args = parser.parse_args()
    if args.threads < 1:
        parser.error("--threads must be positive")
    torch.set_num_threads(args.threads)
    config = default_config(args.experiment)
    for key in ("tasks", "seed", "window", "horizon"):
        value = getattr(args, key)
        if value is not None:
            config[key] = value
    checkpoint = train(config, args.out or Path("runs") / args.experiment)
    plot_training(checkpoint)
    print(f"Saved {checkpoint}")


if __name__ == "__main__":
    main()
